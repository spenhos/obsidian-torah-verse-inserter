let current: Lang = "en";

function detect(): Lang {
	let raw = "en";
	try {
		if (typeof getLanguage === "function") raw = getLanguage() || "en";
	} catch {
		raw = "en";
	}
	const two = raw.toLowerCase().split(/[-_]/)[0];
	return SUPPORTED.includes(two as Lang) ? (two as Lang) : "en";
}

export function initI18n(): void {
	current = detect();
}

/** Idioma para etiquetas de libros: español, hebreo o inglés (fallback). */
export function currentLang(): "es" | "en" | "he" {
	if (current === "es") return "es";
	if (current === "he") return "he";
	return "en";
}

export function t(key: string, params?: Record<string, string | number>): string {
	let s = translations[current]?.[key] ?? translations.en[key] ?? key;
	if (params) {
		for (const p of Object.keys(params)) {
			s = s.split("{" + p + "}").join(String(params[p]));
		}
	}
	return s;
}
